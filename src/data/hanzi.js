function normalize(raw, levelId) {
  return raw.map((item, index) => ({
    id: `${levelId}-${index}`,
    level: levelId,
    char: item[0],
    pinyin: item[1],
    radical: item[2],
    strokes: item[3],
    words: item[4],
    sentence: item[5],
    emoji: item[6]
  }))
}

export const HANZI_LEVELS = Object.keys(RAW).map((id) => ({
  ...LEVEL_META[id],
  items: normalize(RAW[id], id)
}))

export const HANZI_ALL = HANZI_LEVELS.flatMap((l) => l.items)

export function getHanziLevel(levelId) {
  return HANZI_LEVELS.find((l) => l.id === levelId) || HANZI_LEVELS[0]
}
